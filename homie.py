#!/usr/bin/env python3
"""
homie.py — Homie firmware CLI

  python homie.py generate                  Generate src/homie.cpp + data/*.yml from device.yml
  python homie.py build                     Generate then compile firmware
  python homie.py push                      Flash firmware to device
  python homie.py push --fs                 Flash firmware + filesystem
  python homie.py push --fs-only            Flash filesystem only
  python homie.py push --port COM3          Specify serial port
  python homie.py monitor                   Open serial monitor
  python homie.py monitor --port COM3
  python homie.py clean                     Clean build artifacts
  python homie.py devices                   List attached serial devices
  python homie.py envs                      List available PlatformIO board environments
  python homie.py config status             Show config overlay state
  python homie.py config init               Bootstrap ~/.config/eBus/config.yml from example
  python homie.py config stage              Copy overlay to data/config.yml
"""

import sys
import os
import argparse
import subprocess
import shutil
from pathlib import Path
import yaml

# ── paths ──────────────────────────────────────────────────────────────────────

ROOT         = Path(__file__).resolve().parent
LIB_DIR      = ROOT / "lib"
SRC_DIR      = ROOT / "src"
DATA_DIR     = ROOT / "data"
CONFIG_DIR   = Path.home() / ".config" / "eBus"
CONFIG_OVERLAY = CONFIG_DIR / "config.yml"
CONFIG_TARGET  = DATA_DIR / "config.yml"
CONFIG_EXAMPLE = DATA_DIR / "config.yml.example"

# ── pio helper ─────────────────────────────────────────────────────────────────

def find_pio() -> str:
    candidates = [
        Path.home() / ".platformio/penv/Scripts/pio.exe",  # Windows
        Path.home() / ".platformio/penv/bin/pio",           # Unix/Mac
    ]
    for p in candidates:
        if p.exists():
            return str(p)
    if shutil.which("pio"):
        return "pio"
    print("ERROR: PlatformIO not found.", file=sys.stderr)
    print("Install: https://platformio.org/install/cli", file=sys.stderr)
    sys.exit(1)

def pio_run(board: str, targets: list, port: str = None) -> int:
    pio = find_pio()
    cmd = [pio, "run", "-e", board]
    for t in targets:
        cmd += ["-t", t]
    if port:
        cmd += ["--upload-port", port]
    return subprocess.run(cmd, cwd=ROOT).returncode

# ── device.yml helpers ─────────────────────────────────────────────────────────

def load_device_yml(path: Path) -> dict:
    if not path.exists():
        print(f"ERROR: {path} not found.", file=sys.stderr)
        print("Create one from the format in doc/GenerateHomieApp.md", file=sys.stderr)
        sys.exit(1)
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)

def get_board(cfg: dict) -> str:
    board = cfg.get("device", {}).get("board")
    if not board:
        print("ERROR: device.yml missing device.board", file=sys.stderr)
        sys.exit(1)
    return board

# ── generate ───────────────────────────────────────────────────────────────────

_HOMIE_CPP_HEADER = """\
// AUTO-GENERATED by homie.py generate — do not edit manually.
// Regenerate with: python homie.py generate
//
// Static node instances for this Homie device.
// All objects are statically allocated; constructors run before setup().

#include <homie.h>
"""

def find_component_yml(component: str) -> Path:
    parts = component.split("/")
    if len(parts) == 2:
        p = LIB_DIR / parts[0] / f"{parts[1]}.yml"
        if p.exists():
            return p
        raise FileNotFoundError(f"Component yml not found: {p}")
    for sub in LIB_DIR.iterdir():
        if sub.is_dir():
            candidate = sub / f"{component}.yml"
            if candidate.exists():
                return candidate
    raise FileNotFoundError(f"No component yml found for: {component!r}")

def fmt_ctor(template: str, node_id: str, config: dict) -> str:
    result = template.replace("{id}", node_id)
    for k, v in (config or {}).items():
        result = result.replace(f"{{config.{k}}}", str(v))
    return result

def cmd_generate(args) -> None:
    device_yml = Path(args.device_yml)
    cfg        = load_device_yml(device_yml)
    device     = cfg.get("device", {})
    nodes_cfg  = cfg.get("nodes", [])

    includes        = []
    decls           = []
    prop_static_decls = []  # static Property <var>;
    prop_reg_body   = []    # body of register_homie_properties()
    setups          = []
    loops           = []
    homie_nodes     = []

    for entry in nodes_cfg:
        component = entry["component"]
        node_id   = entry.get("id")
        node_cfg  = entry.get("config", {})

        comp_path = find_component_yml(component)
        with open(comp_path, encoding="utf-8") as f:
            comp = yaml.safe_load(f)

        gen = comp.get("generator")
        if not gen:
            print(f"WARNING: no generator block in {comp_path} — skipping")
            continue

        cls       = gen["class"]
        header    = gen["header"]
        ctor_tmpl = gen["constructor"]

        if not node_id:
            comp_nodes = comp.get("nodes", [])
            node_id = comp_nodes[0]["id"] if comp_nodes else component.split("/")[-1]

        includes.append(f"#include <{header}>")
        decls.append(f"{cls} {node_id}{fmt_ctor(ctor_tmpl, node_id, node_cfg)};")
        setups.append(f"    {node_id}.setup();")
        loops.append(f"    {node_id}.loop();")

        comp_nodes = comp.get("nodes", [])
        single = len(comp_nodes) == 1
        for n in comp_nodes:
            nc = dict(n)
            effective_node_id = node_id if single else n["id"]
            if single:
                nc["id"] = node_id
            homie_nodes.append(nc)

            # Generate static Property declarations and registration code
            properties = n.get("properties", [])
            node_name = n.get("name", effective_node_id)
            node_type = n.get("type", "generic")
            if properties:
                if prop_reg_body:
                    prop_reg_body.append("")
                # Use NodeEntity's getNodeId() so the id is not duplicated as a string literal
                id_expr = f'{node_id}.getNodeId()' if single else f'"{effective_node_id}"'
                prop_reg_body.append(f'    _node = device->addNode({id_expr}, "{node_name}", "{node_type}");')
                prop_reg_body.append(f'    if (_node) {{')
                for prop in properties:
                    prop_id  = prop["id"]
                    prop_var = f"_prop_{effective_node_id}_{prop_id}"
                    prop_static_decls.append(f"static Property {prop_var};")
                    prop_reg_body.append(f'        {prop_var}.setNode(_node);')
                    prop_reg_body.append(f'        {prop_var}.setId("{prop_id}");')
                    prop_reg_body.append(f'        {prop_var}.setName("{prop["name"]}");')
                    prop_reg_body.append(f'        {prop_var}.setDatatype("{prop["datatype"]}");')
                    if prop.get("unit"):
                        prop_reg_body.append(f'        {prop_var}.setUnit("{prop["unit"]}");')
                    if prop.get("settable", False):
                        prop_reg_body.append(f'        {prop_var}.setSettable(true);')
                    if not prop.get("retained", True):
                        prop_reg_body.append(f'        {prop_var}.setRetained(false);')
                    prop_reg_body.append(f'        _node->addProperty(&{prop_var});')
                prop_reg_body.append('    }')

    # src/homie.cpp
    lines = [_HOMIE_CPP_HEADER]
    lines.append("#include <homie/Device.h>")
    lines.append("#include <homie/Property.h>")
    lines.append("")
    if includes:
        lines += includes + [""]
    if decls:
        lines += decls + [""]
    if prop_static_decls:
        lines += ["// Static Homie Property objects — one per node property"] + prop_static_decls + [""]
    lines += ["void register_homie_properties(Device* device) {"]
    if prop_reg_body:
        lines.append("    Node* _node;")
        lines += prop_reg_body
    lines += ["}"]
    lines += ["", "void setup_homie() {"] + (setups or ["    // no nodes configured"]) + ["}"]
    lines += ["", "void loop_homie() {"] + (loops or ["    // no nodes configured"]) + ["}", ""]

    out_cpp = SRC_DIR / "homie.cpp"
    out_cpp.write_text("\n".join(lines), encoding="utf-8")
    print(f"  generated: {out_cpp.relative_to(ROOT)}")

    # data/homie.yml
    homie_doc = {
        "homie":          "5.0.1",
        "name":           device.get("name", "Homie Device"),
        "type":           device.get("type", "generic"),
        "state":          "init",
        "nodes":          homie_nodes,
        "extensions":     [],
        "implementation": "homie-esp32-sdk",
    }
    out_homie = DATA_DIR / "homie.yml"
    with open(out_homie, "w", encoding="utf-8") as f:
        yaml.dump(homie_doc, f, allow_unicode=True, sort_keys=False)
    print(f"  generated: {out_homie.relative_to(ROOT)}")

    # data/config.yml
    wifi     = cfg.get("wifi", {})
    mqtt_cfg = cfg.get("mqtt", {})
    config_doc = {"config": [{
        "wifi_ssid":     wifi.get("ssid",     ""),
        "wifi_password": wifi.get("password", ""),
        "mqtt_host":     mqtt_cfg.get("host",     ""),
        "mqtt_port":     mqtt_cfg.get("port",     1883),
        "mqtt_username": mqtt_cfg.get("username", ""),
        "mqtt_password": mqtt_cfg.get("password", ""),
        "device_id":     device.get("id",   ""),
        "device_name":   device.get("name", ""),
        "device_type":   device.get("type", ""),
    }]}
    out_config = DATA_DIR / "config.yml"
    with open(out_config, "w", encoding="utf-8") as f:
        yaml.dump(config_doc, f, allow_unicode=True, sort_keys=False)
    print(f"  generated: {out_config.relative_to(ROOT)}")

    board = device.get("board", "<board>")
    print(f"\n{len(nodes_cfg)} node(s), board: {board}")

# ── build ──────────────────────────────────────────────────────────────────────

def cmd_build(args) -> None:
    print("--- generate ---")
    cmd_generate(args)
    print("\n--- build ---")
    cfg   = load_device_yml(Path(args.device_yml))
    board = get_board(cfg)
    print(f"pio run -e {board}\n")
    rc = pio_run(board, [])
    if rc != 0:
        print(f"\nBUILD FAILED (exit {rc})", file=sys.stderr)
        sys.exit(rc)
    bin_path = ROOT / ".pio" / "build" / board / "firmware.bin"
    if bin_path.exists():
        print(f"\nfirmware: {bin_path}  ({bin_path.stat().st_size / 1024:.1f} KB)")

# ── push ───────────────────────────────────────────────────────────────────────

def cmd_push(args) -> None:
    print("--- generate ---")
    cmd_generate(args)

    cfg   = load_device_yml(Path(args.device_yml))
    board = get_board(cfg)
    port  = getattr(args, "port", None)

    upload_fw = not args.fs_only
    upload_fs = args.fs or args.fs_only

    if upload_fw:
        print(f"\n--- building firmware (env: {board}) ---")
        rc = pio_run(board, [], port)
        if rc != 0:
            print(f"\nBuild FAILED (exit {rc})", file=sys.stderr)
            sys.exit(rc)

        print(f"\n--- uploading firmware (env: {board}) ---")
        rc = pio_run(board, ["upload"], port)
        if rc != 0:
            print(f"\nFirmware upload FAILED (exit {rc})", file=sys.stderr)
            sys.exit(rc)
        bin_path = ROOT / ".pio" / "build" / board / "firmware.bin"
        if bin_path.exists():
            print(f"flashed: {bin_path}  ({bin_path.stat().st_size / 1024:.1f} KB)")

    if upload_fs:
        print(f"\n--- uploading filesystem (env: {board}) ---")
        rc = pio_run(board, ["buildfs", "uploadfs"], port)
        if rc != 0:
            print(f"\nFilesystem upload FAILED (exit {rc})", file=sys.stderr)
            sys.exit(rc)

    print("\ndone.")

# ── monitor ────────────────────────────────────────────────────────────────────

def cmd_monitor(args) -> None:
    cfg   = load_device_yml(Path(args.device_yml))
    board = get_board(cfg)
    pio   = find_pio()
    cmd   = [pio, "device", "monitor", "-e", board]
    if args.port:
        cmd += ["--port", args.port]
    subprocess.run(cmd, cwd=ROOT)

# ── clean ──────────────────────────────────────────────────────────────────────

def cmd_clean(args) -> None:
    cfg   = load_device_yml(Path(args.device_yml))
    board = get_board(cfg)
    pio_run(board, ["clean"])

# ── devices ────────────────────────────────────────────────────────────────────

def cmd_devices(args) -> None:
    pio = find_pio()
    subprocess.run([pio, "device", "list", "--serial"], cwd=ROOT)

# ── envs ───────────────────────────────────────────────────────────────────────

def cmd_envs(args) -> None:
    pio = find_pio()
    result = subprocess.run(
        [pio, "project", "config", "--json-output"],
        cwd=ROOT, capture_output=True, text=True
    )
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        sys.exit(result.returncode)
    import json
    for section in json.loads(result.stdout):
        if section[0].startswith("env:"):
            print(section[0][4:])

# ── config ─────────────────────────────────────────────────────────────────────

def cmd_config(args) -> None:
    sub = args.config_cmd

    if sub == "status":
        print(f"overlay path:  {CONFIG_OVERLAY}")
        if CONFIG_OVERLAY.exists():
            size = CONFIG_OVERLAY.stat().st_size
            print(f"overlay state: present ({size} bytes)")
        else:
            print("overlay state: MISSING — run: python homie.py config init")
        print(f"target path:   {CONFIG_TARGET}")
        if CONFIG_TARGET.exists():
            if CONFIG_OVERLAY.exists() and _files_identical(CONFIG_TARGET, CONFIG_OVERLAY):
                print("target state:  in sync with overlay")
            else:
                print("target state:  present but drifted — run: python homie.py config stage")
        else:
            print("target state:  MISSING — run: python homie.py config stage")
        print(f"example path:  {CONFIG_EXAMPLE}")

    elif sub == "init":
        if CONFIG_OVERLAY.exists():
            print(f"overlay already exists: {CONFIG_OVERLAY}")
            print("Edit it directly; this command will not overwrite it.")
        else:
            CONFIG_DIR.mkdir(parents=True, exist_ok=True)
            shutil.copy(CONFIG_EXAMPLE, CONFIG_OVERLAY)
            print(f"created: {CONFIG_OVERLAY}")
            print("Edit it with your broker, credentials, and device settings.")
            print("Then run: python homie.py config stage")

    elif sub == "stage":
        if not CONFIG_OVERLAY.exists():
            print(f"ERROR: overlay not found at {CONFIG_OVERLAY}", file=sys.stderr)
            print("Run: python homie.py config init", file=sys.stderr)
            sys.exit(1)
        shutil.copy(CONFIG_OVERLAY, CONFIG_TARGET)
        print(f"staged: {CONFIG_OVERLAY}")
        print(f"    to: {CONFIG_TARGET}")

    else:
        print(f"Unknown config subcommand: {sub!r}", file=sys.stderr)
        print("Use: status | init | stage", file=sys.stderr)
        sys.exit(1)

def _files_identical(a: Path, b: Path) -> bool:
    return a.read_bytes() == b.read_bytes()

# ── main ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        prog="homie.py",
        description="Homie firmware CLI — generate, build, and deploy ESP32 firmware",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="\n".join([
            "examples:",
            "  python homie.py generate",
            "  python homie.py build",
            "  python homie.py push",
            "  python homie.py push --port COM3",
            "  python homie.py push --fs",
            "  python homie.py push --fs-only",
            "  python homie.py monitor --port COM3",
            "  python homie.py clean",
            "  python homie.py devices",
            "  python homie.py envs",
            "  python homie.py config status",
            "  python homie.py config init",
            "  python homie.py config stage",
        ]),
    )

    dev_yml_arg = dict(nargs="?", default="device.yml", metavar="device.yml",
                       help="device config file (default: device.yml)")
    port_arg    = dict(default=None, metavar="PORT",
                       help="serial port, e.g. COM3 or /dev/ttyUSB0 (auto-detected if omitted)")

    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("generate", help="Generate src/homie.cpp + data/*.yml from device.yml")
    p.add_argument("device_yml", **dev_yml_arg)

    p = sub.add_parser("build", help="Generate then compile firmware via PlatformIO")
    p.add_argument("device_yml", **dev_yml_arg)

    p = sub.add_parser("push", help="Flash firmware (and optionally filesystem) to device")
    p.add_argument("device_yml", **dev_yml_arg)
    p.add_argument("--port", **port_arg)
    g = p.add_mutually_exclusive_group()
    g.add_argument("--fs",      action="store_true", help="flash firmware + filesystem")
    g.add_argument("--fs-only", action="store_true", help="flash filesystem only")

    p = sub.add_parser("monitor", help="Open serial monitor")
    p.add_argument("device_yml", **dev_yml_arg)
    p.add_argument("--port", **port_arg)

    p = sub.add_parser("clean", help="Clean PlatformIO build artifacts")
    p.add_argument("device_yml", **dev_yml_arg)

    sub.add_parser("devices", help="List attached serial devices")

    p = sub.add_parser("envs", help="List available PlatformIO board environments")
    p.add_argument("device_yml", **dev_yml_arg)

    p = sub.add_parser("config", help="Manage device config overlay")
    p.add_argument("config_cmd", choices=["status", "init", "stage"],
                   metavar="status|init|stage")

    args = parser.parse_args()

    dispatch = {
        "generate": cmd_generate,
        "build":    cmd_build,
        "push":     cmd_push,
        "monitor":  cmd_monitor,
        "clean":    cmd_clean,
        "devices":  cmd_devices,
        "envs":     cmd_envs,
        "config":   cmd_config,
    }
    dispatch[args.command](args)

if __name__ == "__main__":
    main()
