// Print sink that FNV-1a hashes whatever serializeJson() writes to it, so the
// $description `version` can be derived without a second buffer or truncation.
class Fnv1aPrint : public Print {
 public:
  size_t write(uint8_t c) override {
    _hash ^= c;
    _hash *= 16777619u;
    return 1;
  }
  size_t write(const uint8_t* data, size_t len) override {
    for (size_t i = 0; i < len; i++) write(data[i]);
    return len;
  }
  uint32_t hash() { return _hash; }
 private:
  uint32_t _hash = 2166136261u;
};

// JSON serialization — single document to avoid cross-doc copy issues
size_t Device::serialize(char* buffer, size_t bufferSize) {
  JsonDocument json;
  json[HOMIE_HOMIE]   = HOMIE_SPEC_VERSION;
  json[HOMIE_VERSION] = 0;   // placeholder; set to the content hash below
  json[HOMIE_NAME] = _name;
  json[HOMIE_TYPE] = _type;
  // Homie 5 nested-device hierarchy. `children` is always present (empty for a
  // leaf), matching the reference SDK; `root`/`parent` appear only on non-root
  // devices. The tree is referenced by device-id, not embedded.
  JsonArray children = json[HOMIE_CHILDREN].to<JsonArray>();
  for (Device* c = _first_child; c; c = c->_next_sibling) {
    children.add(c->getId());
  }
  if (_parent) {
    json[HOMIE_ROOT]   = root()->getId();
    json[HOMIE_PARENT] = _parent->getId();
  }
  JsonObject nodes_obj = json[HOMIE_NODES].to<JsonObject>();
  for (int i = 0; i < _num_nodes; i++) {
    JsonObject node_obj = nodes_obj[_nodes[i]->id()].to<JsonObject>();
    node_serialize_into(*_nodes[i], node_obj);
  }
  // Homie 5 requires `version` to change whenever the description does. Hash the
  // document with the placeholder version: deterministic, so an unchanged
  // description keeps its version (and A9 still sees identical bytes).
  Fnv1aPrint content_hash;
  serializeJson(json, content_hash);
  json[HOMIE_VERSION] = content_hash.hash();
  // Surface silent truncation: serializeJson() caps output at bufferSize-1.
  // Per-device buffer sizing for large/nested trees is tracked in Epic A.
  size_t needed = measureJson(json);
  if (needed + 1 > bufferSize) {
    Serial.printf("Device: ERROR $description needs %u bytes but buffer is %u — TRUNCATED (raise MAX_DATA_LEN)\n",
                  (unsigned)needed, (unsigned)bufferSize);
  }
  return serializeJson(json, buffer, bufferSize);
}

void Device::publishState() {
  char state_topic[128] = {0};
  snprintf(state_topic, sizeof(state_topic), "%s%s", topic(), HOMIE_$STATE);
  const char* state_str = device_state_to_cstr(_state);

  Serial.printf("DEVICE publish: %s -> '%s'\n", state_topic, state_str);

  // MQTTClient publish: (topic, payload, retained, qos). $state is retained -> QoS 2 (C4)
  if (!_mqtt_client->publish(state_topic, state_str, true, homie_qos(true))) {
      Serial.println("MQTT publish: $state failed");
  }
}

// Heap-allocated on first use (not a static array): on the arduino-esp32 3.x build,
// total .bss/.data footprint crossing a threshold somewhere between ~97KB and
// ~105KB corrupts/exhausts a small early-boot heap region that FreeRTOS's own
// vApplicationGetIdleTaskMemory() draws its very first allocation from during
// vTaskStartScheduler() — before app_main()/setup() ever runs. This single
// MAX_DATA_LEN (8192 byte) static array was the exact size of the margin between
// a working and a crashing build. Allocating it lazily here (first reached only
// from Device::publish(), i.e. from setup(), long after the scheduler has already
// started successfully) avoids counting against that early static-footprint budget.
static char* _description_json = nullptr;
static char* description_json_buf() {
  if (_description_json == nullptr) {
    _description_json = new char[MAX_DATA_LEN];
  }
  return _description_json;
}

// FNV-1a, 32-bit. Cheap, no library, fine for change-detection on an ESP32 (the
// issue calls out avoiding SHA-256). Not cryptographic — collisions are harmless
// here (worst case: a redundant republish, never a missed-but-needed one within
// the same content, since identical content always hashes equal).
static uint32_t fnv1a_32(const char* data, size_t len) {
  uint32_t h = 2166136261u;
  for (size_t i = 0; i < len; i++) {
    h ^= (uint8_t)data[i];
    h *= 16777619u;
  }
  return h;
}

// Serialize $description into the shared static buffer and return its hash. The C++
// $description is deterministic (`version` is a hash of the content, not a fresh
// timestamp like the python SDK), so the whole serialized buffer is hashed directly.
uint32_t Device::buildDescription(size_t* out_len) {
  char* buf = description_json_buf();
  size_t len = toJson(buf, MAX_DATA_LEN);
  if (out_len) *out_len = len;
  return fnv1a_32(buf, len);
}

void Device::publish() {

  // Homie 5: a device's $description may only CHANGE while $state is init,
  // disconnected, or lost. Warn (rather than silently swallow) if it's published
  // while ready/sleeping — the caller should cycle the device through init first
  // (see addChildLive() and the ordered add/remove protocols).
  if (_state == DEVICE_STATE_READY || _state == DEVICE_STATE_SLEEPING) {
    Serial.printf("Device '%s': WARNING $description published while $state=%s — Homie 5 "
                  "requires init/disconnected/lost; cycle through init first\n",
                  _id, device_state_to_cstr(_state));
  }

  //$description
  size_t len = 0;
  uint32_t h = buildDescription(&len);
  // A9: suppress a byte-identical retained republish — avoids the redundant payload
  // and (when wrapped in a state cycle) a gratuitous controller resync.
  if (_has_description_hash && h == _last_description_hash) {
    Serial.printf("DEVICE publish: $description unchanged (hash %08lx, %u bytes) — skipping republish\n",
                  (unsigned long)h, (unsigned)len);
  } else {
    Serial.println("DEVICE publish: $description");
    char top[128] = {0};
    snprintf(top, sizeof(top), "%s%s", topic(), HOMIE_$DESCRIPTION);
    Serial.printf("DEVICE: $description JSON size: %d bytes\n", len);
    // MQTTClient publish: (topic, payload, retained, qos). $description retained -> QoS 2 (C4)
    if (!_mqtt_client->publish(top, description_json_buf(), true, homie_qos(true))) {
        Serial.println("MQTT publish: $description failed");
    } else {
        _last_description_hash = h;
        _has_description_hash  = true;
    }
  }

  //nodes
  Serial.println("DEVICE publish: nodes");
  for (int i = 0; i < _num_nodes; i++) {
    Serial.printf("DEVICE publish: node: %s\n", _nodes[i]->name());
    _nodes[i]->publish();
  }

}

const char* device_state_to_cstr(DeviceState state) {
    switch (state) {
        case DEVICE_STATE_INIT:         return HOMIE_STATE_INIT;
        case DEVICE_STATE_READY:        return HOMIE_STATE_READY;
        case DEVICE_STATE_DISCONNECTED: return HOMIE_STATE_DISCONNECTED;
        case DEVICE_STATE_SLEEPING:     return HOMIE_STATE_SLEEPING;
        case DEVICE_STATE_LOST:         return HOMIE_STATE_LOST;
        default:                        return HOMIE_STATE_UNKNOWN;
    }
}

// Safe for exact matches only; not case-insensitive
DeviceState device_state_from_cstr(const char* str) {
    if (strcmp(str, "init") == 0)         return DEVICE_STATE_INIT;
    if (strcmp(str, "ready") == 0)        return DEVICE_STATE_READY;
    if (strcmp(str, "disconnected") == 0) return DEVICE_STATE_DISCONNECTED;
    if (strcmp(str, "sleeping") == 0)     return DEVICE_STATE_SLEEPING;
    if (strcmp(str, "lost") == 0)         return DEVICE_STATE_LOST;
    return DEVICE_STATE_UNKNOWN;
}
