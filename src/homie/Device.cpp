Device::Device() {
    _num_nodes = 0;
    _state = DeviceState::DEVICE_STATE_INIT;
}

void Device::addNodePropertiesFromConfigJson(Node* n, JsonVariant node_json, bool subscribe) {
    JsonVariant props = node_json[HOMIE_PROPERTIES].as<JsonArray>();
    for(JsonVariant json_prop : props.as<JsonArray>()) {
      if (json_prop.is<JsonObject>()) {
        Property* prop = new Property();
        prop->setNode(n); // required: set the parent node on the property before anything else
        prop->setMQTTClient(_mqtt_client);
        JsonObject props_obj = json_prop.as<JsonObject>();
        property_from_dict(*prop, &props_obj); // Initialize property from JsonObject
        n->addProperty(prop);
        if (subscribe && prop->settable()) {
          prop->subscribe();
        }
      }
    }
}

void Device::init(const char* name, const char* id, const char* type, MQTTClient* mqtt_client) {
  setName(name);
  setId(id);
  setType(type);
  _mqtt_client = mqtt_client;
  // Topic uses device ID (e.g. homie/5/ESP32POEISO_A1B2C3/)
  snprintf(_topic, sizeof(_topic), "%s/%s/", HOMIE_TOPIC_PREFIX, id);
  // Nodes and properties are registered by register_homie_properties() — generated by ebus-esp32
}

Node* Device::addNode(const char* id, const char* name, const char* type) {
    if (_num_nodes >= MAX_NODES) {
        Serial.printf("Device: ERROR node limit (%d) reached — '%s' NOT added\n", MAX_NODES, id);
        return nullptr;
    }
    Node* n = new Node();
    n->setDevice(this);
    n->setId(id);
    n->setName(name);
    n->setType(type);
    n->setTopic(_topic);
    n->setMQTTClient(_mqtt_client);
    Serial.printf("Device: Node: Adding '%s' id '%s'\n", name, id);
    _nodes[_num_nodes++] = n;
    return n;
}

Node* Device::addNode(JsonVariant node, const char* topic) {
    if (_num_nodes >= MAX_NODES) {
        Serial.printf("Device: ERROR node limit (%d) reached — node NOT added\n", MAX_NODES);
        return nullptr;
    }
    Node* n =  new Node();
    n->setDevice(this);
    if (jsonExists(node[HOMIE_ID])) n->setId(node[HOMIE_ID].as<const char*>());
    if (jsonExists(node[HOMIE_NAME])) n->setName(node[HOMIE_NAME].as<const char*>());
    if (jsonExists(node[HOMIE_TYPE])) n->setType(node[HOMIE_TYPE].as<const char*>());
    n->setTopic(topic);
    Serial.printf("Device: Node: Adding '%s' with id '%s'\n", n->name(), n->id());
    _nodes[_num_nodes++] = n;
    return n;
}

// Declarative node registration from a PropertyDesc table (D2). Heap-free: the caller
// owns the Property storage; we just wire each descriptor into storage[i].
Node* Device::addNode(const char* id, const char* name, const char* type,
                      const PropertyDesc* descs, Property* storage, size_t count) {
  Node* n = addNode(id, name, type);   // existing 3-arg create
  if (!n) return nullptr;
  for (size_t i = 0; i < count; i++) {
    const PropertyDesc& d = descs[i];
    n->addProperty(&storage[i], d.id, d.name, to_homie(d.datatype),
                   d.unit, d.settable, d.retained, d.format);
    if (d.supports_target) storage[i].setSupportsTarget(true);
  }
  return n;
}

Node* Device::getNode(const char* id) {
  for (int i = 0; i < _num_nodes; i++) {
      if (strcmp(_nodes[i]->id(), id) == 0) {
          return _nodes[i];
      }
  }
  Serial.printf("Device: Node '%s' not found\n", id);
  return nullptr;
}

// --- Nested-device tree (Homie 5 parent/child) ---

void Device::addChild(Device* child) {
  if (!child) return;
  child->_parent = this;
  child->_next_sibling = nullptr;
  // Append to the sibling list so children keep insertion order.
  if (!_first_child) {
    _first_child = child;
  } else {
    Device* s = _first_child;
    while (s->_next_sibling) s = s->_next_sibling;
    s->_next_sibling = child;
  }
  _num_children++;
  Serial.printf("Device '%s': added child '%s'\n", _id, child->getId());
}

Device* Device::root() {
  Device* d = this;
  while (d->_parent) d = d->_parent;
  return d;
}

const char* Device::parentId() {
  return _parent ? _parent->getId() : nullptr;
}

const char* Device::rootId() {
  return _parent ? root()->getId() : nullptr;
}

// Publish this device and every descendant: each emits its own $state +
// $description + node values over the shared (root) MQTT connection. Depth-first,
// parents before children. (The ordered Homie add-child INIT/READY protocol is
// A6; this is the straight whole-tree publish.)
void Device::publishTree() {
  publishState();
  publish();
  for (Device* c = _first_child; c; c = c->_next_sibling) {
    c->publishTree();
  }
}

// Republish $state for this device and every descendant. Used on MQTT reconnect:
// the broker's Last Will set the ROOT's $state to "lost" (which, per Homie 5,
// cascades the lost state to the whole tree), so on reconnect every device must
// re-assert its own $state to clear the cascade.
void Device::publishStateTree() {
  publishState();
  for (Device* c = _first_child; c; c = c->_next_sibling) {
    c->publishStateTree();
  }
}

// Runtime add following the Homie 5 ordered protocol (convention §"Adding children"):
// publish the child fully (init -> $description -> ready), THEN cycle the parent
// (init -> updated $description listing the child -> ready). Cycling through init is
// what lets the parent's $description change (it may only change in init/disc/lost).
//
// The parent cycle goes through notifyStructuralChange(), so wrapping several
// addChildLive() calls in a `Device::StateTransition` on the parent collapses them
// into ONE parent INIT->$description->READY flap (A8 batching).
void Device::addChildLive(Device* child) {
  if (!child) return;
  addChild(child);                       // link first: the child can now resolve root/parent
  // 1. publish the child fully — its own init -> $description (with root/parent) +
  //    nodes -> ready. A child starts in INIT, so the guard's entry is a no-op and
  //    its exit publishes the child's description and brings it to ready.
  {
    StateTransition t(child);
  }
  // 2. tell the parent its child set changed (suppressed if the parent is itself
  //    mid-transition — then the enclosing scope republishes once for the batch).
  notifyStructuralChange();
}

// Runtime remove (convention §"Removing children"): cycle the parent (init ->
// $description without the child -> ready), THEN clear the child's retained topics
// starting with $state (an empty $state means the device ceases to exist).
//
// The parent cycle goes through notifyStructuralChange(), so a batch of
// removeChildLive() calls inside a `Device::StateTransition` collapses to one flap.
void Device::removeChildLive(Device* child) {
  if (!child) return;
  // 1. detach so our $description omits the child, then republish it (one flap, or
  //    batched into an enclosing StateTransition).
  unlinkChild(child);
  notifyStructuralChange();
  // 2. clear the child's retained topics ($state empty => device ceases to exist).
  child->clearRetained();
  child->_parent = nullptr;
}

// --- Batched state transitions (A8) ---

// Enter a transition scope. Only the outermost entry announces INIT. setState()
// publishes only on a state CHANGE, so for a brand-new device that already starts in
// INIT we publish $state=init explicitly — a fresh child must announce init->...->ready
// like any device. (The python-sdk starts _state as None so its first set_state(INIT)
// publishes; C++ defaults to DEVICE_STATE_INIT, hence the explicit publishState here.)
void Device::beginTransition() {
  _transition_depth++;
  if (_transition_depth == 1) {
    if (_state != DEVICE_STATE_INIT) {
      setState(DEVICE_STATE_INIT);
    } else {
      publishState();
    }
  }
}

// Exit a transition scope. Only the outermost exit publishes the consolidated
// $description and returns to READY; inner exits just decrement. Leaving the scope
// (depth -> 0) BEFORE publish() is deliberate: notifyStructuralChange() must not
// suppress this final, intended republish.
void Device::endTransition() {
  if (_transition_depth == 1) {
    _transition_depth = 0;
    publish();
    setState(DEVICE_STATE_READY);
  } else if (_transition_depth > 0) {
    _transition_depth--;
  }
}

// Republish $description after a structural change (a child was added or removed).
// Suppressed while mid-transition — the outermost endTransition() publishes once for
// the whole batch. Before the device is ready (boot), just publish with no flap;
// once ready, a full INIT->$description->READY cycle (the only legal way to change
// $description while live).
void Device::notifyStructuralChange() {
  if (_transition_depth > 0) return;
  // A9: peek the serialized description; if it's unchanged, skip the whole INIT->
  // READY flap (not just the publish) so controllers aren't forced to resync over a
  // no-op structural change.
  uint32_t h = buildDescription(nullptr);
  if (_has_description_hash && h == _last_description_hash) {
    Serial.printf("Device '%s': structural change left $description unchanged — no flap\n", _id);
    return;
  }
  if (_state != DEVICE_STATE_READY) {
    publish();
    return;
  }
  setState(DEVICE_STATE_INIT);
  publish();
  setState(DEVICE_STATE_READY);
}

// Proxy state management (G1): map source-link health to the proxied device's state.
void Device::setSourceConnected(bool up) {
  DeviceState want = up ? DEVICE_STATE_READY : DEVICE_STATE_LOST;
  if (_state == want) return;
  Serial.printf("Device '%s': proxy source %s -> $state %s\n",
                _id, up ? "connected" : "disconnected", device_state_to_cstr(want));
  setState(want);   // publishes $state; the description/values are untouched
}

void Device::unlinkChild(Device* child) {
  if (_first_child == child) {
    _first_child = child->_next_sibling;
  } else {
    for (Device* s = _first_child; s; s = s->_next_sibling) {
      if (s->_next_sibling == child) { s->_next_sibling = child->_next_sibling; break; }
    }
  }
  child->_next_sibling = nullptr;
  if (_num_children > 0) _num_children--;
}

// Publish a zero-length retained payload to this device's $state, $description, and
// each property topic — removing the retained messages. $state first, per the spec.
void Device::clearRetained() {
  if (!_mqtt_client) return;
  char top[160] = {0};
  snprintf(top, sizeof(top), "%s%s", topic(), HOMIE_$STATE);
  _mqtt_client->publish(top, "", true, homie_qos(true));
  snprintf(top, sizeof(top), "%s%s", topic(), HOMIE_$DESCRIPTION);
  _mqtt_client->publish(top, "", true, homie_qos(true));
  for (int i = 0; i < _num_nodes; i++) {
    _nodes[i]->clearRetained();
  }
  // A9: the retained $description is now empty, so forget the cached hash — the next
  // publish() must re-send even if the content matches what we had before clearing.
  _has_description_hash = false;
}

void Device::setState(DeviceState state) {
  DeviceState previous_state = _state;
  _state = state;

  //state change?
  if (_state != previous_state) {
    publishState();
  }
}

