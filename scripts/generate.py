#!/usr/bin/env python3
"""
Homie firmware generator
Usage: python3 scripts/generate.py [device.yml]

Reads a unified device.yml and emits:
  src/homie.cpp      — static object declarations + setup_homie() / loop_homie()
  data/homie.yml     — merged Homie convention topology (from component YAMLs)
  data/config.yml    — runtime config (wifi, mqtt, device identity)

Each component in lib/<bus>/<name>.yml must contain a `generator:` block:
  generator:
    class: ClassName
    header: bus/name.h
    constructor: '("{id}")'          # {id} = node id; {config.KEY} = node config values
"""

import sys
import argparse
from pathlib import Path
import yaml

PROJECT_ROOT = Path(__file__).resolve().parent.parent
LIB_DIR      = PROJECT_ROOT / "lib"
SRC_DIR      = PROJECT_ROOT / "src"
DATA_DIR     = PROJECT_ROOT / "data"

_HEADER = """\
// AUTO-GENERATED by scripts/generate.py — do not edit manually.
// Regenerate with: python3 scripts/generate.py device.yml
//
// Static node instances for this Homie device.
// All objects are statically allocated; constructors run before setup().

#include <homie.h>
"""

def load_yaml(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)

def find_component_yml(component: str) -> Path:
    """Resolve 'modbus/sht20' → lib/modbus/sht20.yml, searching if no slash given."""
    parts = component.split("/")
    if len(parts) == 2:
        path = LIB_DIR / parts[0] / f"{parts[1]}.yml"
        if path.exists():
            return path
        raise FileNotFoundError(f"Component yml not found: {path}")
    # bare name — search all lib subdirs
    for sub in LIB_DIR.iterdir():
        if sub.is_dir():
            candidate = sub / f"{component}.yml"
            if candidate.exists():
                return candidate
    raise FileNotFoundError(f"No component yml found for: {component!r}")

def format_constructor(template: str, node_id: str, config: dict) -> str:
    """Substitute {id} and {config.KEY} in a constructor arg template."""
    result = template.replace("{id}", node_id)
    for key, val in (config or {}).items():
        result = result.replace(f"{{config.{key}}}", str(val))
    return result

def generate(device_yml_path: str) -> None:
    path = Path(device_yml_path)
    if not path.exists():
        print(f"ERROR: {path} not found", file=sys.stderr)
        sys.exit(1)

    cfg = load_yaml(path)

    device    = cfg.get("device", {})
    nodes_cfg = cfg.get("nodes", [])

    includes     = []
    declarations = []
    setup_calls  = []
    loop_calls   = []
    homie_nodes  = []

    for entry in nodes_cfg:
        component  = entry["component"]
        node_id    = entry.get("id")
        node_cfg   = entry.get("config", {})

        comp_path = find_component_yml(component)
        comp      = load_yaml(comp_path)

        gen = comp.get("generator")
        if not gen:
            print(f"WARNING: no generator block in {comp_path} — skipping")
            continue

        cls      = gen["class"]
        header   = gen["header"]
        ctor_tmpl = gen["constructor"]

        # Fall back to first node id in the component yml when not specified
        if not node_id:
            comp_nodes = comp.get("nodes", [])
            node_id = comp_nodes[0]["id"] if comp_nodes else component.split("/")[-1]

        ctor_args = format_constructor(ctor_tmpl, node_id, node_cfg)

        includes.append(f"#include <{header}>")
        declarations.append(f"{cls} {node_id}{ctor_args};")
        setup_calls.append(f"    {node_id}.setup();")
        loop_calls.append(f"    {node_id}.loop();")

        # Collect homie node defs.
        # Single-node component: override id with the instance id from device.yml.
        # Multi-node component: keep each node's own id (the instance id is just
        # the C++ object name; the Homie topology stays as the component defines it).
        comp_nodes = comp.get("nodes", [])
        single = len(comp_nodes) == 1
        for n in comp_nodes:
            node_copy = dict(n)
            if single:
                node_copy["id"] = node_id
            homie_nodes.append(node_copy)

    # ── src/homie.cpp ──────────────────────────────────────────────────────────
    lines = [_HEADER]
    if includes:
        lines += includes
        lines.append("")
    if declarations:
        lines += declarations
        lines.append("")
    lines.append("void setup_homie() {")
    lines += setup_calls or ["    // no nodes configured"]
    lines.append("}")
    lines.append("")
    lines.append("void loop_homie() {")
    lines += loop_calls or ["    // no nodes configured"]
    lines.append("}")
    lines.append("")

    out_cpp = SRC_DIR / "homie.cpp"
    out_cpp.write_text("\n".join(lines), encoding="utf-8")
    print(f"  generated: {out_cpp.relative_to(PROJECT_ROOT)}")

    # ── data/homie.yml ─────────────────────────────────────────────────────────
    homie_doc = {
        "homie":          "5.0.1",
        "name":           device.get("name", "Homie Device"),
        "type":           device.get("type", "generic"),
        "state":          "init",
        "nodes":          homie_nodes,
        "extensions":     [],
        "implementation": "homie-esp32-sdk",
    }
    out_homie = DATA_DIR / "homie.yml"
    homie_text = yaml.dump(homie_doc, allow_unicode=True, sort_keys=False)
    out_homie.write_text(homie_text, encoding="utf-8")
    print(f"  generated: {out_homie.relative_to(PROJECT_ROOT)}")
    print()
    for line in homie_text.splitlines():
        print(f"    {line}")

    # ── data/config.yml ────────────────────────────────────────────────────────
    wifi     = cfg.get("wifi", {})
    mqtt_cfg = cfg.get("mqtt", {})
    config_doc = {
        "config": [{
            "wifi_ssid":      wifi.get("ssid",     ""),
            "wifi_password":  wifi.get("password", ""),
            "mqtt_host":      mqtt_cfg.get("host",     ""),
            "mqtt_port":      mqtt_cfg.get("port",     1883),
            "mqtt_username":  mqtt_cfg.get("username", ""),
            "mqtt_password":  mqtt_cfg.get("password", ""),
            "device_id":      device.get("id",   ""),
            "device_name":    device.get("name", ""),
            "device_type":    device.get("type", ""),
        }]
    }
    out_config = DATA_DIR / "config.yml"
    config_text = yaml.dump(config_doc, allow_unicode=True, sort_keys=False)
    out_config.write_text(config_text, encoding="utf-8")
    print(f"  generated: {out_config.relative_to(PROJECT_ROOT)}")
    print()
    for line in config_text.splitlines():
        print(f"    {line}")

    board = device.get("board", "<board>")
    print(f"\n{len(nodes_cfg)} node(s), board: {board}")
    print(f"build with: make build PIO_ENV={board}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Homie firmware generator")
    parser.add_argument("device_yml", nargs="?", default="device.yml",
                        help="Path to unified device config (default: device.yml)")
    args = parser.parse_args()
    generate(args.device_yml)
